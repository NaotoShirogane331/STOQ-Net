"""Path-independent installed runtime identity; no model imports or device queries."""

import ast
import platform
import re
import site
from importlib import metadata
from pathlib import Path


def _is_vendored_distribution(distribution):
    """Return true for distribution metadata nested inside an installed package."""
    distribution_path = getattr(distribution, "_path", None)
    if distribution_path is None:
        return False
    roots = [*site.getsitepackages(), site.getusersitepackages()]
    for raw_root in roots:
        try:
            relative = Path(distribution_path).resolve().relative_to(Path(raw_root).resolve())
        except ValueError:
            continue
        return len(relative.parts) > 1
    return False


def runtime_inventory():
    """Freeze all resolved distributions and Torch's static runtime build fields.

    RECORD hashes identify installed neural/operator builds without loading their
    extensions. Absolute prefixes, entrypoint scripts and generated bytecode are
    deliberately not scientific identity. Missing build evidence fails closed.
    """
    implementations = {"torch", "numpy", "mamba-ssm", "causal-conv1d", "neuralforecast", "xlstm"}
    packages = {}
    for distribution in metadata.distributions():
        if _is_vendored_distribution(distribution):
            continue
        name = re.sub(r"[-_.]+", "-", distribution.metadata["Name"]).lower()
        if name in packages:
            raise RuntimeError("NOT_READY: ambiguous installed distribution: " + name)
        entry = {"version": distribution.version}
        if name in implementations:
            records = []
            for file in distribution.files or ():
                path = str(file).replace("\\", "/")
                if (path.startswith("/") or ".." in path.split("/") or
                        any(part.endswith((".dist-info", ".egg-info")) for part in path.split("/")) or
                        not path.endswith((".py", ".so", ".pyd", ".dll", ".dylib"))):
                    continue
                if file.hash is None:
                    raise RuntimeError("NOT_READY: implementation RECORD hash unavailable: " + name + "/" + path)
                records.append({"path": path, "hash": file.hash.mode + "=" + file.hash.value,
                                "size_bytes": file.size})
            if not records:
                raise RuntimeError("NOT_READY: installed implementation provenance unavailable: " + name)
            entry["implementation_records"] = sorted(records, key=lambda item: item["path"])
        packages[name] = entry
    if not {"torch", "numpy"}.issubset(packages):
        raise RuntimeError("NOT_READY: required neural runtime distributions missing")
    # Parse source literals, never import torch or initialize CUDA for this check.
    source = metadata.distribution("torch").locate_file("torch/version.py").read_text(encoding="utf-8")
    fields = {"__version__", "cuda", "hip", "git_version"}
    build = {}
    for node in ast.parse(source).body:
        targets = node.targets if isinstance(node, ast.Assign) else [node.target] if isinstance(node, ast.AnnAssign) else []
        for target in targets:
            if isinstance(target, ast.Name) and target.id in fields:
                value = ast.literal_eval(node.value)
                if value is not None and not isinstance(value, str):
                    raise RuntimeError("NOT_READY: unsupported Torch build metadata")
                build[target.id] = value
    if set(build) != fields:
        raise RuntimeError("NOT_READY: incomplete Torch build metadata")
    return {"python": {"implementation": platform.python_implementation(), "version": platform.python_version()},
            "distributions": dict(sorted(packages.items())), "torch_build": build}
